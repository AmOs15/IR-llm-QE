# ==========================================
# 共通制約 (Common Constraints)
# すべてのプロンプトで共通して適用されるルール
# ==========================================
COMMON_CONSTRAINTS = """
# Output Guidelines (共通制約)

1. **出力形式**:
   - 結果は必ず JSON形式の配列 `["語句1", "語句2", ...]` のみを出力してください。
   - JSONの前後には説明文、挨拶、Markdownのコードブロック記号（```json 等）を含めないでください。
   - `{"words": [...]}` などのオブジェクト形式ではなく、フラットなリスト `[...]` を返してください。

2. **拡張語の選定基準**:
   - **同義語・言い換え**: 文脈を変えずに置き換え可能な語（例: "スマホ" -> "スマートフォン"）。
   - **下位・具体化**: クエリが広範な場合、検索意図に含まれる具体的な固有名詞や用語。
   - **表記揺れ**: 漢字/かな/カタカナ、アルファベットの別表記。
   - **関連語**: 検索ヒット率を高めるための密接に関連するキーワード。

3. **禁止事項 (Drift Prevention)**:
   - クエリの意図と逆の意味を持つ語（対義語）は禁止。
   - 文章やフレーズ（文）は禁止。単語または短い複合語（Noun Phrase）に限定すること。
   - ストップワード（これ、それ、方法、理由など）単体での追加は避けること。
   - クエリに含まれていない「独自の新しい事実」を捏造しないこと（ハルシネーション防止）。

4. **品質管理**:
   - 重複する語は除去すること。
   - 配列内の順序は、検索における重要度が高い順（確信度が高い順）に並べること。
"""

